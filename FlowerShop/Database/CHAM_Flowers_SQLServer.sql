CREATE DATABASE CHAMFlowersDb;
GO
USE CHAMFlowersDb;
GO

CREATE TABLE Users (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    FullName NVARCHAR(100) NOT NULL,
    Full_name NVARCHAR(100) NOT NULL,
    Email NVARCHAR(100) NOT NULL UNIQUE,
    Password VARCHAR(255) NOT NULL,
    Phone VARCHAR(20) NULL,
    Address NVARCHAR(255) NOT NULL,
    Avatar NVARCHAR(255) NULL,
    Role VARCHAR(50) NOT NULL DEFAULT 'Customer',
    IsActive BIT NOT NULL DEFAULT 1,
    BirthDate DATETIME NULL,
    TotalSpent DECIMAL(12,2) NOT NULL DEFAULT 0,
    IsVip BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME NULL
);

CREATE TABLE Categories (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    Name NVARCHAR(100) NOT NULL,
    IsActive BIT NOT NULL DEFAULT 1,
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME NULL
);

CREATE TABLE FlowerCategories (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    Name NVARCHAR(100) NOT NULL,
    Description NVARCHAR(255) NULL,
    ImageUrl NVARCHAR(255) NULL,
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE TABLE Suppliers (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    Name NVARCHAR(100) NOT NULL,
    Address NVARCHAR(200) NULL,
    Phone NVARCHAR(50) NULL,
    Email NVARCHAR(100) NULL,
    IsActive BIT NOT NULL DEFAULT 1,
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME NULL
);

CREATE TABLE Products (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    Name NVARCHAR(200) NOT NULL,
    IsFeatured BIT NOT NULL DEFAULT 0,
    IsHotDeal BIT NOT NULL DEFAULT 0,
    Slug NVARCHAR(250) NOT NULL,
    CategoryId INT NOT NULL FOREIGN KEY REFERENCES Categories(Id),
    SupplierId INT NULL FOREIGN KEY REFERENCES Suppliers(Id),
    FlowerCategoryId INT NULL FOREIGN KEY REFERENCES FlowerCategories(Id),
    Price DECIMAL(12,2) NOT NULL,
    OriginalPrice DECIMAL(12,2) NULL,
    Description NVARCHAR(MAX) NULL,
    IsActive BIT NOT NULL DEFAULT 1,
    StockQuantity INT NOT NULL DEFAULT 0,
    ExpiryDate DATETIME NULL,
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME NULL
);

CREATE TABLE ProductImages (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    ProductId INT NOT NULL FOREIGN KEY REFERENCES Products(Id) ON DELETE CASCADE,
    ImageUrl NVARCHAR(500) NOT NULL,
    IsMain BIT NOT NULL DEFAULT 0
);

CREATE TABLE Orders (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    UserId INT NULL FOREIGN KEY REFERENCES Users(Id),
    RecipientName NVARCHAR(100) NOT NULL,
    RecipientPhone VARCHAR(20) NOT NULL,
    DeliveryAddress NVARCHAR(255) NOT NULL,
    DeliveryDate DATETIME NOT NULL,
    ShippingCarrier NVARCHAR(100) NOT NULL,
    ShippingFee DECIMAL(12,2) NOT NULL DEFAULT 30000,
    CouponCode NVARCHAR(50) NULL,
    DiscountAmount DECIMAL(12,2) NOT NULL DEFAULT 0,
    PaymentMethod NVARCHAR(100) NOT NULL,
    Total DECIMAL(12,2) NOT NULL,
    Status NVARCHAR(100) NOT NULL,
    Note NVARCHAR(500) NULL,
    VnPayTransactionNo NVARCHAR(100) NULL,
    PaidAmount DECIMAL(12,2) NULL,
    PaidDate DATETIME NULL,
    IsPaid BIT NOT NULL DEFAULT 0,
    StockDeducted BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE TABLE OrderItems (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    OrderId INT NOT NULL FOREIGN KEY REFERENCES Orders(Id) ON DELETE CASCADE,
    ProductId INT NOT NULL FOREIGN KEY REFERENCES Products(Id),
    Quantity INT NOT NULL,
    UnitPrice DECIMAL(12,2) NOT NULL
);

CREATE TABLE Reviews (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    ProductId INT NOT NULL FOREIGN KEY REFERENCES Products(Id) ON DELETE CASCADE,
    UserId INT NOT NULL FOREIGN KEY REFERENCES Users(Id) ON DELETE CASCADE,
    Rating INT NOT NULL,
    Content NVARCHAR(MAX) NOT NULL,
    Status INT NOT NULL DEFAULT 0,
    IsApproved BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE TABLE ProductReviews (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    ProductId INT NOT NULL FOREIGN KEY REFERENCES Products(Id) ON DELETE CASCADE,
    UserId INT NOT NULL FOREIGN KEY REFERENCES Users(Id) ON DELETE CASCADE,
    Rating INT NOT NULL,
    Comment NVARCHAR(MAX) NOT NULL,
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE TABLE Carts (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    UserId INT NULL FOREIGN KEY REFERENCES Users(Id),
    SessionId NVARCHAR(100) NULL,
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE(),
    UpdatedAt DATETIME NULL
);

CREATE TABLE CartItems (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    CartId INT NOT NULL FOREIGN KEY REFERENCES Carts(Id) ON DELETE CASCADE,
    ProductId INT NOT NULL FOREIGN KEY REFERENCES Products(Id) ON DELETE CASCADE,
    Quantity INT NOT NULL,
    UnitPrice DECIMAL(12,2) NOT NULL
);

CREATE TABLE HotDealPopups (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    Title NVARCHAR(150) NULL,
    Subtitle NVARCHAR(300) NULL,
    ImageUrl NVARCHAR(500) NOT NULL,
    ProductId INT NULL FOREIGN KEY REFERENCES Products(Id),
    DiscountPercent INT NULL,
    CouponCode NVARCHAR(50) NULL,
    IsActive BIT NOT NULL DEFAULT 1,
    StartDate DATETIME NULL,
    EndDate DATETIME NULL,
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE TABLE Banners (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    Title NVARCHAR(200) NOT NULL,
    Subtitle NVARCHAR(300) NULL,
    ImageUrl NVARCHAR(500) NOT NULL,
    LinkUrl NVARCHAR(255) NULL,
    ButtonText NVARCHAR(80) NULL,
    DisplayOrder INT NOT NULL DEFAULT 1,
    IsActive BIT NOT NULL DEFAULT 1,
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE TABLE ChatConversations (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    UserId INT NULL FOREIGN KEY REFERENCES Users(Id),
    CustomerName NVARCHAR(100) NOT NULL,
    CustomerEmail NVARCHAR(100) NULL,
    SessionKey NVARCHAR(100) NOT NULL,
    Status NVARCHAR(50) NOT NULL DEFAULT N'Đang xử lý',
    IsCustomerOnline BIT NOT NULL DEFAULT 1,
    UnreadAdminCount INT NOT NULL DEFAULT 0,
    UnreadCustomerCount INT NOT NULL DEFAULT 0,
    LastMessageAt DATETIME NOT NULL DEFAULT GETDATE(),
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE()
);

CREATE TABLE ChatMessages (
    Id INT IDENTITY(1,1) PRIMARY KEY,
    ConversationId INT NOT NULL FOREIGN KEY REFERENCES ChatConversations(Id) ON DELETE CASCADE,
    SenderRole NVARCHAR(30) NOT NULL,
    SenderName NVARCHAR(100) NOT NULL,
    Content NVARCHAR(MAX) NOT NULL,
    MessageType NVARCHAR(30) NOT NULL DEFAULT 'Text',
    AttachmentUrl NVARCHAR(255) NULL,
    IsRead BIT NOT NULL DEFAULT 0,
    CreatedAt DATETIME NOT NULL DEFAULT GETDATE()
);
